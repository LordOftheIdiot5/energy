const assert=require('node:assert/strict'),fs=require('node:fs');
const {validateCatalog,validateRoutes,filterRows,enrich,STATUS}=require('../atlas-gem-pipelines.js');
const tab=JSON.parse(fs.readFileSync('data/gem-gas-202511/gem-gas-pipelines-202511-v1.json','utf8'));
const geo=JSON.parse(fs.readFileSync('data/gem-gas-202511/gem-gas-pipeline-routes-202511-v1.geojson','utf8'));
assert.equal(validateCatalog(tab),tab);
const ids=new Set(tab.rows.map(r=>r.id));
assert.equal(ids.size,4246);
assert.equal(validateRoutes(geo,ids),geo);
assert.equal(geo.features.length,3921);
const enriched=enrich(tab,geo);
assert.equal(enriched.features.length,3921);
assert.equal(enriched.features[0].properties.pipeline_id,geo.features[0].properties.pipeline_id);
assert.equal(tab.rows.filter(r=>r.status==='Status not reported').length,1);
assert.equal(filterRows(tab.rows,{status:'operating'}).length,2975);
assert.equal(filterRows(tab.rows,{status:'construction'}).length,282);
assert.equal(filterRows(tab.rows,{status:'proposed'}).length,611);
const example=tab.rows.find(r=>r.status==='operating'&&r.start_country);
assert.ok(example);
assert.equal(filterRows(tab.rows,{status:example.status,country:example.start_country,search:example.id})[0].id,example.id);
assert.equal(filterRows(tab.rows,{search:'xx-absent-nordl-pipeline-xx'}).length,0);
assert.equal(ids.size-new Set(geo.features.map(f=>f.properties.pipeline_id)).size,325);
assert.throws(()=>validateCatalog({...tab,license:'unknown'}));
assert.throws(()=>validateCatalog({...tab,rows:tab.rows.slice(0,-1)}));
assert.throws(()=>validateRoutes({...geo,features:geo.features.slice(0,-1)},ids));
assert.throws(()=>validateRoutes({...geo,features:[{...geo.features[0],geometry:{type:'Point',coordinates:[0,0]}},...geo.features.slice(1)]},ids));
console.log('PASS GEM 4,246/3,921, source rights, all statuses, 325 unmapped, route geometry, country/search filters');
