const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const base=process.env.ENERGY_TEST_URL||'http://127.0.0.1:8766/';
 const source=JSON.parse(fs.readFileSync('data/eia860m-generators-v1.json','utf8'));
 const known=source.rows.find(r=>r.inventory==='planned'&&r.state==='AZ'&&r.status.includes('Under construction'));
 assert.ok(known,'Official EIA planned test fixture missing');
 try{for(const width of [1440,390]){
  const page=await browser.newPage({viewport:{width,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'#energyMap',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.NordlEnergyAtlas?.isDetailed(),null,{timeout:60000});
  let response=await page.request.get(base+'data/eia860m/index-v1.json');
  assert.equal(response.status(),200);
  const idx=await response.json();assert.equal(idx.counts.mapped_rows,40048);
  assert.deepEqual(idx.inventories.map(x=>x.records).sort((a,b)=>a-b),[1676,2357,7303,28712]);
  response=await page.request.get(base+'data/eia860m/planned-v1.json');
  assert.equal(response.status(),200);const planned=await response.json();
  assert.equal(planned.rows.length,2357);
  await page.locator('#globalUsGenerators').check();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.usRecords==='2357',null,{timeout:60000});
  await page.locator('#usGeneratorView').click();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.usMarkers)>0,null,{timeout:30000});
  const markerCount=await page.locator('#atlasMap .atlas-us-generator-marker').count();
  assert.ok(markerCount>0&&markerCount<900,'US map markers missing or unbounded: '+markerCount);
  await page.locator('#atlasFitSource').selectOption('us');
  await page.locator('#atlasFitActive').click();
  const controls=page.locator('#globalUsGenerators').locator('xpath=ancestor::div[contains(@class,"atlas-digital-controls")]');
  await controls.locator('details').evaluate(e=>e.open=true);
  await page.locator('#usGeneratorState').selectOption(known.state);
  await page.locator('#usGeneratorStage').selectOption(known.status);
  await page.locator('#usGeneratorFind').fill(known.id);
  await page.waitForFunction(id=>[...document.getElementById('usGeneratorResults').options].some(x=>x.value===id),known.id,{timeout:15000});
  await page.locator('#usGeneratorResults').selectOption(known.id);
  const inspection=await page.locator('#usGeneratorInspector').innerText();
  assert.ok(inspection.includes(known.plant));
  assert.ok(inspection.includes(known.status));
  assert.ok(inspection.includes('not measured electricity production'));
  assert.ok(await page.locator('#usGeneratorInspector a[href*="eia.gov"]').isVisible());
  await page.locator('#usGeneratorInventory').selectOption('operating');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.usRecords==='28712',null,{timeout:60000});
  await page.locator('#usGeneratorView').click();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.usMarkers)>0,null,{timeout:30000});
  assert.ok(await page.locator('#usGeneratorStage option').count()>3,'Missing actual operating status distinctions');
  await page.locator('#globalUkProjects').check();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.ukRecords==='14388',null,{timeout:60000});
  await page.locator('#globalUsGenerators').uncheck();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.usMarkers==='0');
  assert.ok(await page.locator('#globalUkProjects').isChecked(),'US toggle must not disable UK projects');
  assert.deepEqual(errors,[],'No uncaught map errors on '+width+'px');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+4),'Responsive viewport '+width);
  console.log('PASS US EIA live atlas '+width+' · 40,048 source mapped, '+markerCount+' visible planned markers, original EIA statuses, capacity, independent UK');
  await page.close();
 }}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
