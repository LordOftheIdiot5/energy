const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const base=process.env.ENERGY_TEST_URL||'http://127.0.0.1:8766/';
 const source=JSON.parse(fs.readFileSync('data/nacei-oilgas-2017-v1.json','utf8'));
 try{for(const width of [1440,390]){
  const page=await browser.newPage({viewport:{width,height:950}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'#energyMap',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.NordlEnergyAtlas?.isDetailed(),null,{timeout:60000});
  const res=await page.request.get(base+'data/nacei-oilgas-2017-v1.json');assert.equal(res.status(),200);
  const data=await res.json();assert.equal(data.source_period,'2017-08');assert.equal(data.rows.refineries.length,168);
  assert.equal(await page.locator('#globalNaceiHistoric').isChecked(),false);
  await page.locator('#globalNaceiHistoric').check();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.naceiRecords==='1278',null,{timeout:60000});
  await page.locator('#naceiView').click();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.naceiMarkers)>0,null,{timeout:20000});
  const initial=await page.locator('#atlasMap .atlas-nacei-marker').count();
  assert.ok(initial>0&&initial<700,'Unbounded historical gas markers '+initial);
  await page.locator('#naceiKind').selectOption('lng_terminals');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.naceiRecords==='15',null,{timeout:15000});
  await page.locator('#naceiView').click();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.naceiMarkers)>0,null,{timeout:20000});
  const box=page.locator('#globalNaceiHistoric').locator('xpath=ancestor::div[contains(@class,"atlas-digital-controls")]');
  await box.locator('details').evaluate(e=>e.open=true);
  const selected=source.rows.lng_terminals[0];
  await page.locator('#naceiSearch').fill(selected.id);
  await page.waitForFunction(id=>[...document.getElementById('naceiResults').options].some(x=>x.value===id),selected.id,{timeout:20000});
  await page.locator('#naceiResults').selectOption(selected.id);
  const inspection=await page.locator('#naceiInspector').innerText();
  assert.ok(inspection.includes(selected.facility));
  assert.ok(inspection.includes('2017 historical'));
  assert.ok(inspection.includes('not reported')||inspection.includes('not independently'));
  assert.ok(await page.locator('#naceiInspector a[href*="nrcan.gc.ca"]').isVisible());
  await page.locator('#naceiKind').selectOption('refineries');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.naceiRecords==='168',null,{timeout:15000});
  await page.locator('#naceiView').click();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.naceiMarkers)>0,null,{timeout:20000});
  await page.locator('#globalUsGenerators').check();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.usRecords)>0,null,{timeout:60000});
  await page.locator('#globalNaceiHistoric').uncheck();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.naceiMarkers==='0',null,{timeout:10000});
  assert.equal(await page.locator('#globalUsGenerators').isChecked(),true);
  assert.deepEqual(errors,[], 'Map runtime errors '+width);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+4),'Mobile width overflow '+width);
  console.log('PASS NACEI historical atlas '+width+' · gas '+initial+' visible clusters, 15 LNG, 168 refineries, 2017 provenance, US independence');
  await page.close();
 }}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
