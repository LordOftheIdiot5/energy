const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const base=process.env.ENERGY_TEST_URL||'http://127.0.0.1:8766/';
 const source=JSON.parse(fs.readFileSync('data/gem-gas-202511/gem-gas-pipelines-202511-v1.json','utf8'));
 const geo=JSON.parse(fs.readFileSync('data/gem-gas-202511/gem-gas-pipeline-routes-202511-v1.geojson','utf8'));
 const mappedIds=new Set(geo.features.map(f=>f.properties.pipeline_id));
 const known=source.rows.find(r=>r.status==='operating'&&mappedIds.has(r.id)&&r.start_country);
 const unmapped=source.rows.find(r=>!mappedIds.has(r.id));
 assert.ok(known&&unmapped,'Official GEM records with and without route geometry required');
 try{for(const width of [1440,390]){
  const page=await browser.newPage({viewport:{width,height:940}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'#energyMap',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.NordlEnergyAtlas?.isDetailed(),null,{timeout:60000});
  assert.equal(await page.locator('#globalGemPipelines').isChecked(),false);
  let r=await page.request.get(base+'data/gem-gas-202511/gem-gas-pipelines-202511-v1.json');assert.equal(r.status(),200);
  r=await page.request.get(base+'data/gem-gas-202511/gem-gas-pipeline-routes-202511-v1.geojson');assert.equal(r.status(),200);
  await page.locator('#globalGemPipelines').check();
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.gemRecords==='2975',null,{timeout:65000});
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.gemRenderedFeatures==='3921',null,{timeout:45000});
  await page.locator('#gemView').click();
  const live=await page.waitForFunction(()=>{
   const m=window.NordlEnergyAtlas.getMap(),el=document.getElementById('atlasMap');if(!m?.getLayer('nordl-gem-gas-routes'))return false;
   return m.queryRenderedFeatures([[0,0],[el.clientWidth,el.clientHeight]],{layers:['nordl-gem-gas-routes']}).length>0;
  },null,{timeout:45000});
  assert.ok(live);
  const found=await page.evaluate(()=>{const m=window.NordlEnergyAtlas.getMap();return {visibility:m.getLayoutProperty('nordl-gem-gas-routes','visibility')||'visible',source:m.getSource('nordl-gem-gas-lines')!=null};});
  assert.equal(found.source,true);assert.equal(found.visibility,'visible');
  const controls=page.locator('#globalGemPipelines').locator('xpath=ancestor::div[contains(@class,"atlas-digital-controls")]');
  await controls.locator('details').evaluate(e=>e.open=true);
  await page.locator('#gemCountry').selectOption(known.start_country);
  await page.locator('#gemSearch').fill(known.id);
  await page.waitForFunction(id=>[...document.getElementById('gemResults').options].some(o=>o.value===id),known.id,{timeout:20000});
  await page.locator('#gemResults').selectOption(known.id);
  let details=await page.locator('#gemPipelineInspector').innerText();
  assert.ok(details.includes(known.name));assert.ok(details.includes('November 2025'));
  assert.ok(details.includes('CC BY 4.0')&&details.includes('not survey-accurate'));
  await page.locator('#gemStatus').selectOption('construction');
  await page.locator('#gemCountry').selectOption('');
  await page.locator('#gemSearch').fill('');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.gemRecords==='282',null,{timeout:15000});
  await page.locator('#gemStatus').selectOption('proposed');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.gemRecords==='611',null,{timeout:15000});
  await page.locator('#gemStatus').selectOption('');
  await page.waitForFunction(()=>document.getElementById('atlasMap').dataset.gemRecords==='4246',null,{timeout:15000});
  await page.locator('#gemSearch').fill(unmapped.id);
  await page.waitForFunction(id=>[...document.getElementById('gemResults').options].some(o=>o.value===id),unmapped.id,{timeout:15000});
  await page.locator('#gemResults').selectOption(unmapped.id);
  details=await page.locator('#gemPipelineInspector').innerText();
  assert.ok(details.includes('No mapped route supplied'));
  await page.locator('#globalNaceiHistoric').check();
  await page.waitForFunction(()=>Number(document.getElementById('atlasMap').dataset.naceiRecords)>0,null,{timeout:60000});
  await page.locator('#globalGemPipelines').uncheck();
  await page.waitForFunction(()=>window.NordlEnergyAtlas.getMap().getLayoutProperty('nordl-gem-gas-routes','visibility')==='none',null,{timeout:15000});
  assert.ok(await page.locator('#globalNaceiHistoric').isChecked(),'GEM cannot disable historical NACEI layer');
  assert.deepEqual(errors,[], 'Page runtime errors at '+width+' px');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+4),'Responsive width '+width);
  console.log('PASS GEM global pipelines '+width+' · 3921 GPU routes, 4246 projects, 325 unmapped, separate statuses, license, independent NACEI');
  await page.close();
 }}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
